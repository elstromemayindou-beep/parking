create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name text not null,
  city text not null,
  country text not null,
  address text not null default '',
  phone text not null default '',
  currency text not null default 'XAF',
  created_by uuid not null references auth.users (id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.branch_members (
  branch_id bigint not null references public.branches (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null check (role in (
    'PROPRIETAIRE',
    'GERANT',
    'RECEPTIONNISTE',
    'MECANICIEN',
    'LAVEUR',
    'AGENT_PARKING',
    'CAISSIER'
  )),
  created_at timestamptz not null default now(),
  primary key (branch_id, user_id)
);

create table if not exists public.branch_data (
  branch_id bigint not null references public.branches (id) on delete cascade,
  collection text not null,
  payload jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (branch_id, collection)
);

create or replace function public.is_branch_member(target_branch_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.branch_members
    where branch_id = target_branch_id
      and user_id = (select auth.uid())
  );
$$;

create or replace function public.create_branch_with_owner(
  branch_name text,
  branch_city text,
  branch_country text,
  branch_address text default '',
  branch_phone text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_branch_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  insert into public.branches (name, city, country, address, phone, created_by)
  values (
    trim(branch_name),
    trim(branch_city),
    trim(branch_country),
    trim(coalesce(branch_address, '')),
    trim(coalesce(branch_phone, '')),
    auth.uid()
  )
  returning id into new_branch_id;

  insert into public.branch_members (branch_id, user_id, role)
  values (new_branch_id, auth.uid(), 'PROPRIETAIRE');

  return new_branch_id;
end;
$$;

alter table public.branches enable row level security;
alter table public.branch_members enable row level security;
alter table public.branch_data enable row level security;

drop policy if exists "Members can read their branches" on public.branches;
create policy "Members can read their branches"
  on public.branches for select to authenticated
  using (public.is_branch_member(id));

drop policy if exists "Users can read their memberships" on public.branch_members;
create policy "Users can read their memberships"
  on public.branch_members for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Members can read branch data" on public.branch_data;
create policy "Members can read branch data"
  on public.branch_data for select to authenticated
  using (public.is_branch_member(branch_id));

drop policy if exists "Members can create branch data" on public.branch_data;
create policy "Members can create branch data"
  on public.branch_data for insert to authenticated
  with check (public.is_branch_member(branch_id));

drop policy if exists "Members can update branch data" on public.branch_data;
create policy "Members can update branch data"
  on public.branch_data for update to authenticated
  using (public.is_branch_member(branch_id))
  with check (public.is_branch_member(branch_id));

drop policy if exists "Members can delete branch data" on public.branch_data;
create policy "Members can delete branch data"
  on public.branch_data for delete to authenticated
  using (public.is_branch_member(branch_id));

revoke all on function public.create_branch_with_owner(text, text, text, text, text) from public;
grant execute on function public.create_branch_with_owner(text, text, text, text, text) to authenticated;
grant execute on function public.is_branch_member(bigint) to authenticated;
grant select on public.branches, public.branch_members to authenticated;
grant select, insert, update, delete on public.branch_data to authenticated;
